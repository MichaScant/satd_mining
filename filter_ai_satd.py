"""Filter to AI-GENERATED technical debt in code changes, and mark who merged it.

Motivation: Stage 1's cohort regex treats *any* bot as "AI", so dependency/CI
automation (renovate, github-actions, release bots) got swept into the AI cohort —
but those PRs' debt commits are written by humans, not generated by an agent. This
script keeps only debt authored by a genuine CODE-GENERATING agent (Copilot, Devin,
Claude, Cursor, Codex, …) and drops automation + human-authored debt.

Each kept instance is tagged by who put the commit into the repo:
  agent_committed  — the agent's identity is on the commit
  github_merge     — merged via GitHub's merge button (committer 'web-flow')
  human_committed  — a human developer's identity is on the commit
'github_merge' and 'human_committed' are the "AI generated it, a human merged it" cases
-> the basis for "how often do humans let AI-generated debt through?" (merged + human-approved).

Outputs:  ai_generated_satd.csv  (the filtered code-change dataset, human-merged flagged)
Run:  python filter_ai_satd.py [--db db/satd_mining.db] [--out ai_generated_satd.csv]
"""
import argparse
import csv
import re
import sqlite3
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import config

# genuine code-generating agents (NOT dependency/CI/release automation)
CODING_AGENT = re.compile(r"copilot|claude|cursor|devin|codex|sweep|aider|gpt-?engineer|openhands|sourcegraph", re.I)
AUTOMATION = re.compile(r"renovate|dependabot|github-actions|release|backport|translation|lingohub|policy|"
                        r"octo-sts|datadog|coderabbit|snyk|greenkeeper|mergify|auto-pr|semantic-release", re.I)


def commit_identity(author_login, committer_login):
    cm = str(committer_login or "")
    if CODING_AGENT.search(cm):
        return "agent_committed"
    if cm == "web-flow":
        return "github_merge"
    if cm:
        return "human_committed"
    # no committer recorded: fall back to author identity
    return "agent_committed" if CODING_AGENT.search(str(author_login or "")) else "human_committed"


def source_bucket(blob):
    if CODING_AGENT.search(blob):
        return "coding_agent"
    if AUTOMATION.search(blob):
        return "automation_bot"
    return "human_or_unknown"


def main(db, out):
    conn = sqlite3.connect(db); conn.row_factory = sqlite3.Row
    rows = conn.execute("""
        SELECT i.*, p.author AS pr_author, p.state, p.merged_at, p.id AS pr_id,
               cm.author_login, cm.committer_login, cm.co_authors
        FROM satd_instances i
        JOIN prs p ON p.repo=i.repo AND p.pr_number=i.introducing_pr
        LEFT JOIN commits cm ON cm.sha=i.introducing_sha
        WHERE i.channel='code_comment'
    """).fetchall()

    # human-approval lookup per PR (a human explicitly signed off)
    approved = {r["pr_id"] for r in conn.execute(
        "SELECT DISTINCT pr_id FROM review_events WHERE kind='approve' AND actor_type='human'")}

    buckets = Counter()
    kept = []
    for r in rows:
        blob = f'{r["pr_author"]} {r["author_login"]} {r["committer_login"]} {r["co_authors"]}'
        b = source_bucket(blob)
        buckets[b] += 1
        if b != "coding_agent":
            continue
        ident = commit_identity(r["author_login"], r["committer_login"])
        merged_by_human = ident in ("github_merge", "human_committed")
        pr_merged = r["merged_at"] is not None
        kept.append({
            "id": r["id"], "repo": r["repo"], "pr_number": r["introducing_pr"],
            "introducing_sha": r["introducing_sha"], "path": r["path"], "line_span": r["line_span"],
            "satd_type": r["satd_type"], "keyword": r["keyword"],
            "pr_author_agent": r["pr_author"], "git_author": r["author_login"],
            "committer": r["committer_login"], "commit_identity": ident,
            "merged_by_human": int(merged_by_human), "pr_merged": int(pr_merged),
            "human_approved": int(r["pr_id"] in approved),
            "status": r["status"], "resolver_class": r["resolver_class"],
            "survival_days": r["survival_days"],
            "first_pointer_class": r["first_pointer_class"], "first_pointer_level": r["first_pointer_level"],
            "comment": (r["comment_text_raw"] or "")[:160],
        })

    # ---- write CSV ----
    fields = list(kept[0].keys()) if kept else ["id"]
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields); w.writeheader(); w.writerows(kept)

    # ---- summary ----
    pct = lambda n, d: f"{100*n/d:.1f}%" if d else "n/a"
    print("=" * 62)
    print("  AI-GENERATED TECHNICAL DEBT (code changes)")
    print("=" * 62)
    print(f"  from {sum(buckets.values())} code-comment instances:")
    for k in ("coding_agent", "automation_bot", "human_or_unknown"):
        print(f"    {k:18} {buckets[k]:4}  ({pct(buckets[k], sum(buckets.values()))})"
              + ("   <- KEPT" if k == "coding_agent" else "   <- dropped"))
    n = len(kept)
    if not n:
        print("\n  nothing kept."); conn.close(); return

    by_ident = Counter(k["commit_identity"] for k in kept)
    by_type = Counter(k["satd_type"] for k in kept)
    print(f"\n  KEPT {n} AI-generated debt instances")
    print("  by type :", ", ".join(f"{t}={c}" for t, c in by_type.most_common()))
    print("  put in repo by:")
    for ident in ("agent_committed", "github_merge", "human_committed"):
        print(f"    {ident:16} {by_ident[ident]:4}  ({pct(by_ident[ident], n)})")

    # the headline: humans accepting AI-generated debt
    human_merged = [k for k in kept if k["merged_by_human"]]
    hm_merged = [k for k in human_merged if k["pr_merged"]]
    hm_approved = [k for k in human_merged if k["human_approved"]]
    print(f"\n  >> AI generated, a HUMAN merged it: {len(human_merged)} ({pct(len(human_merged), n)})")
    print(f"     of those, PR actually merged:        {len(hm_merged)} ({pct(len(hm_merged), len(human_merged))})")
    print(f"     of those, a human explicitly approved:{len(hm_approved)} ({pct(len(hm_approved), len(human_merged))})")
    print(f"     => humans let AI's self-admitted debt through in {len(hm_approved)} reviewed+approved cases")
    print(f"\n  CSV -> {out}  ({n} rows; human-merged flagged via merged_by_human/commit_identity)")
    print("=" * 62)
    conn.close()


if __name__ == "__main__":
    pkg = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=str(config.DB_PATH))
    ap.add_argument("--out", default=str(pkg / "ai_generated_satd.csv"))
    a = ap.parse_args()
    main(a.db, a.out)
