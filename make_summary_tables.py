"""Generate the key summary tables (markdown) from db/satd_mining.db -> RESULTS_TABLES.md.
Reproducible; consistent with the graphs. Run: python3 make_summary_tables.py"""
import sqlite3, sys
from collections import Counter, defaultdict
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import agents as ag
from stage1_aidev import AIDEV_AGENT_MAP

HERE = Path(__file__).resolve().parent
c = sqlite3.connect(HERE / "db" / "satd_mining.db"); c.row_factory = sqlite3.Row
AGENTS = ["claude", "codex", "cursor", "devin", "jules"]          # AIDev cohort
ALLAG = AGENTS + ["copilot"]                                      # combined cohort (copilot is Suzhen-only)
canon = lambda a: AIDEV_AGENT_MAP.get(str(a or "").strip().lower(), str(a))
out = ["# Summary tables (generated by make_summary_tables.py)\n"]
def pct(n, d): return f"{100*n/d:.1f}%" if d else "—"


# ---- AIDev per-instance agent (code: agent_name; conversation: PR agent) ----
def aidev_rows():
    for r in c.execute(
        "SELECT i.agent_name an, p.agent pag, i.spotter sp, i.how_spotted hw, i.outcome oc, i.n_revisits_resolve nr "
        "FROM satd_instances i JOIN prs p ON p.repo=i.repo AND p.pr_number=i.introducing_pr WHERE p.cohort='aidev'"):
        a = r["an"] if r["an"] else canon(r["pag"])
        if a in AGENTS:
            yield a, r


# Table 1 — RQ1 who spotted (AIDev)
spot = defaultdict(Counter)
for a, r in aidev_rows():
    spot[a][r["sp"]] += 1
out.append("## Table 1 — RQ1: who spotted the SATD (AIDev), per agent\n")
out.append("| Agent | Total | Agent | Developer | Review-bot |")
out.append("|---|---|---|---|---|")
tot1 = Counter()
for a in AGENTS:
    t = sum(spot[a].values()); tot1.update(spot[a])
    out.append(f"| {a} | {t} | {spot[a]['agent']} ({pct(spot[a]['agent'],t)}) | "
               f"{spot[a]['dev']} ({pct(spot[a]['dev'],t)}) | {spot[a]['reviewbot']} ({pct(spot[a]['reviewbot'],t)}) |")
T = sum(tot1.values())
out.append(f"| **Overall** | **{T}** | **{tot1['agent']} ({pct(tot1['agent'],T)})** | "
           f"**{tot1['dev']} ({pct(tot1['dev'],T)})** | **{tot1['reviewbot']} ({pct(tot1['reviewbot'],T)})** |\n")


# Table 2 — RQ1 how agent spotted (AIDev, agent-spotted)
how = defaultdict(Counter)
for a, r in aidev_rows():
    if r["sp"] == "agent" and r["hw"]:
        how[a][r["hw"]] += 1
out.append("## Table 2 — RQ1: how the AGENT spotted its debt (AIDev, agent-spotted), per agent\n")
out.append("| Agent | Agent-spotted n | Spontaneous | Dev-elicited | Review-bot-elicited |")
out.append("|---|---|---|---|---|")
tot2 = Counter()
for a in AGENTS:
    t = sum(how[a].values()); tot2.update(how[a])
    out.append(f"| {a} | {t} | {how[a]['spontaneous']} ({pct(how[a]['spontaneous'],t)}) | "
               f"{how[a]['dev_elicited']} ({pct(how[a]['dev_elicited'],t)}) | "
               f"{how[a]['reviewbot_elicited']} ({pct(how[a]['reviewbot_elicited'],t)}) |")
T = sum(tot2.values())
out.append(f"| **Overall** | **{T}** | **{tot2['spontaneous']} ({pct(tot2['spontaneous'],T)})** | "
           f"**{tot2['dev_elicited']} ({pct(tot2['dev_elicited'],T)})** | "
           f"**{tot2['reviewbot_elicited']} ({pct(tot2['reviewbot_elicited'],T)})** |\n")


# Table 3 — RQ2 outcome of agent-spotted debt (AIDev)
oc = defaultdict(Counter)
for a, r in aidev_rows():
    if r["sp"] == "agent":
        oc[a][r["oc"]] += 1
out.append("## Table 3 — RQ2: outcome of AGENT-spotted debt (AIDev), per agent\n")
out.append("*res% = resolved / (resolved + dropped); excluded = no observable outcome (not in denominator).*\n")
out.append("| Agent | Agent-spotted n | Resolved | Dropped | Excluded | res% (trackable) |")
out.append("|---|---|---|---|---|---|")
tot3 = Counter()
for a in AGENTS:
    res, dr, ex = oc[a]["resolved"], oc[a]["dropped"], oc[a]["excluded"]; tot3.update(oc[a])
    out.append(f"| {a} | {res+dr+ex} | {res} | {dr} | {ex} | {pct(res,res+dr)} |")
res, dr, ex = tot3["resolved"], tot3["dropped"], tot3["excluded"]
out.append(f"| **Overall** | **{res+dr+ex}** | **{res}** | **{dr}** | **{ex}** | **{pct(res,res+dr)}** |\n")


# Table 4 — RQ2 resolution by how-spotted (AIDev, pooled)
byhow = defaultdict(Counter); revs = defaultdict(list)
for a, r in aidev_rows():
    if r["sp"] == "agent" and r["hw"]:
        byhow[r["hw"]][r["oc"]] += 1
        if r["oc"] == "resolved" and r["nr"] is not None:
            revs[r["hw"]].append(r["nr"])
out.append("## Table 4 — RQ2: resolution by how the agent spotted it (AIDev, agent-spotted, pooled)\n")
out.append("| How spotted | Resolved | Trackable (res+dropped) | res% | Mean revisits before fix |")
out.append("|---|---|---|---|---|")
for h in ("spontaneous", "dev_elicited", "reviewbot_elicited"):
    res = byhow[h]["resolved"]; tr = res + byhow[h]["dropped"]
    mr = f"{sum(revs[h])/len(revs[h]):.2f} (n={len(revs[h])})" if revs[h] else "—"
    out.append(f"| {h.replace('_','-')} | {res} | {tr} | {pct(res,tr)} | {mr} |")
out.append("")


# Table 5 — Documentation channel (combined cohort)
def pr_agent():
    m = {}
    for repo, prn, coh, agent, author in c.execute("SELECT repo, pr_number, cohort, agent, author FROM prs"):
        a = (agent or "").strip().lower() or None if coh == "aidev" else ag.classify_actor(author or "")[1]
        if a:
            m[(repo, prn)] = a
    return m
pa = pr_agent()  # used by Table 6
code = Counter(); conv = Counter()
for an, pag, ch in c.execute(
    "SELECT i.agent_name, p.agent, i.channel FROM satd_instances i "
    "JOIN prs p ON p.repo=i.repo AND p.pr_number=i.introducing_pr "
    "WHERE p.cohort='aidev' AND i.spotter='agent'"):      # SAME set as Table 2 / the graphs
    a = an if an else (pag or "").strip().lower()
    if a:
        (code if ch == "code_comment" else conv)[a] += 1
out.append("## Table 5 — Where each agent documents its debt (AIDev agent-spotted), per agent\n")
out.append("*Same agent-spotted set as Table 2, split by channel — so n matches Table 2 exactly. "
           "AIDev cohort (Copilot is Suzhen-only, not shown here).*\n")
out.append("| Agent | n (= agent-spotted, matches Table 2) | In code comments | In PR discussion |")
out.append("|---|---|---|---|")
for a in AGENTS:
    t = code[a] + conv[a]
    out.append(f"| {a} | {t} | {code[a]} ({pct(code[a],t)}) | {conv[a]} ({pct(conv[a],t)}) |")
out.append("")


# Table 6 — Debt type (combined cohort, code SATD)
typ = defaultdict(Counter)
for repo, pr, a_name, t in c.execute(
    "SELECT i.repo, i.introducing_pr, i.agent_name, i.satd_type FROM satd_instances i "
    "WHERE i.channel='code_comment' AND i.introducer_kind='coding_agent'"):
    a = a_name or pa.get((repo, pr))
    if a in ALLAG and t:
        typ[a][t] += 1
out.append("## Table 6 — Debt type of code-comment SATD (combined cohort), per agent\n")
out.append("*design = catch-all (requirement/design debt, renamed old \"feature\" bucket).*\n")
out.append("| Agent | Code SATD n | Design | Bug | Refactoring |")
out.append("|---|---|---|---|---|")
for a in ALLAG:
    t = sum(typ[a].values())
    out.append(f"| {a} | {t} | {typ[a]['design']} ({pct(typ[a]['design'],t)}) | "
               f"{typ[a]['bug']} ({pct(typ[a]['bug'],t)}) | {typ[a]['refactoring']} ({pct(typ[a]['refactoring'],t)}) |")
out.append("")

# ---- Keyword reference: how SATD is detected and sorted into categories ----
import satd_detect as sd
def _fmt(items):  # render a list of patterns/keywords as inline-code, comma-separated
    return ", ".join(f"`{x}`" for x in items)

# sub-concern keyword lists (literal, mirroring graph_admissions.sub())
SUBCONCERN = {
    "interim / stopgap": ["for now", "temporar*", "temp ", "quick fix", "workaround", "work around",
                          "for the time being", "hack"],
    "placeholder / stub": ["placeholder", "stub", "dummy"],
    "hardcoded / magic value": ["hardcod", "hard-cod", "hard cod", "magic number", "magic value"],
    "unsupported / not implemented": ["not supported", "not yet", "nyi", "not implemented",
                                      "only support", "doesn't support", "does not support",
                                      "unsupported", "no support", "not available"],
    "deferred removal / revisit": ["remove this", "should be removed", "get rid", "eventually",
                                   "revisit", "once ", "when we"],
}

out.append("## Table 7 — Keyword reference: how SATD is detected & categorized\n")
out.append("*All patterns matched case-insensitive; first match wins. Readable keyword lists below; "
           "the exact regexes are in `satd_detect.py` (`DEBT_PHRASES`, `DEFERRAL_PHRASES`, `_DEFECT`, "
           "`_HANDLE_ERROR`, `_REFACTOR`) and `graph_admissions.py` (sub-concern).*\n")

out.append("### A. What counts as SATD\n")
out.append("- **Strong markers** (debt on their own): `FIXME`, `HACK`, `XXX`")
out.append("- **Debt phrases** (code comments; a bare `TODO` needs one of these): "
           "`hack`, `hacky`, `kludge`, `workaround`, `temporary`/`temp`, `for now`, `for the time being`, "
           "`quick fix`/`quick and dirty`, `band-aid`, `dirty fix`, `ugly`, `stupid`, `silly`, `nasty`, "
           "`messy`, `crap`, `not sure`, `don't know/understand`, `no idea`, "
           "`should refactor/fix/rewrite/clean/be removed`, `needs (to be) fixed/refactored/reworked/cleaned/revisited`, "
           "`needs work`, `get rid of`, `revisit this`, `come back to`, `this is wrong/broken/a mess/problematic`, "
           "`not (yet) implemented/supported/done/finished`, `placeholder`, `stub`, `will break`, `is broken`, "
           "`remove this`, `rewrite this`, `giving up`")
out.append("- **Conversational deferral** (extra phrases for PR text/dialogue): "
           "`for now`, `follow-up`, `out of scope (for this PR)`, `will/I'll address/handle/fix/do … later`, "
           "`address … in a later/future/follow`, `didn't have time`, `skip(ping)`, `known limitation`, "
           "`leave this/it for`, `revisit later`, `come back to this`, `hardcode(d/ing)`, "
           "`left … as a follow-up`, `not in this/scope`\n")

out.append("### B. Debt TYPE (classify_type — first match wins)\n")
out.append("| Type | Assigned when the comment matches | Keywords |")
out.append("|---|---|---|")
out.append("| **bug** | a defect cue AND **not** an error-handling cue | `bug`, `buggy`, `fix this/the bug`, "
           "`fix issue`, `broken`, `crash(es/ed/ing)`, `wrong`, `incorrect`, `doesn't work`, `does not work`, "
           "`not working`, `corrupt`, `race condition`, `deadlock`, `memory leak`, `null pointer`/`npe`, "
           "`out of bounds/memory/range`, `overflow`, `underflow`, `off-by-one` |")
out.append("| *(excluded from bug)* | error-handling, so routine TODOs aren't mislabelled | "
           "`handle (the) error`, `error handling` |")
out.append("| **refactoring** | a behaviour-preserving reshape cue | `refactor(ing)`, `restructure`, "
           "`reorganize`, `clean up`/`cleanup`, `simplify`, `consolidate`, `decouple`, `modularize`, `extract`, "
           "`move to/into`, `split`, `duplicat*`, `copy-paste`, `DRY`, `dead code` |")
out.append("| **design** | none of the above (catch-all; requirement/design debt, old \"feature\") | — |\n")

out.append("### C. Sub-concern (design-debt sub-type — first match wins)\n")
out.append("| Sub-concern | Keywords |")
out.append("|---|---|")
for name, kws in SUBCONCERN.items():
    out.append(f"| {name} | {_fmt(kws)} |")
out.append("")

txt = "\n".join(out)
(HERE / "RESULTS_TABLES.md").write_text(txt)
print(txt)
c.close()
